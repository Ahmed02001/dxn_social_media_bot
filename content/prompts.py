def get_prompt(post_type: str) -> tuple[str, str]:
    """
    بترجع الـ system prompt والـ user prompt
    لنوع البوست المطلوب
    
    Returns:
        tuple: (system_prompt, user_prompt)
    """
    user_prompt = PROMPTS.get(post_type)
    
    if not user_prompt:
        raise ValueError(f"Unknown post type: {post_type}")
    
    return SYSTEM_PROMPT, user_prompt